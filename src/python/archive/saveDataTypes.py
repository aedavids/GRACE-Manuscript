################################################################################
def archiveModels(outDir : str,
                        dataDict : DiagnosticBundle, 
                        savePanelDict : dict[str, str],
                        resultsDict : dict[str, str],
                        abstract : str = None,
                        ) -> None :
    ''' 
    writes archive in JSON format to disk
    
    '''
    archiveDict = dict()
    archiveDict['abstract'] = abstract
    archiveDict['panels'] = savePanelDict
    archiveDict['results'] = resultsDict
    
    from datetime import datetime
    now = datetime.now()
    archiveDict['runTimeStamp'] =  now.strftime("%Y-%m-%d %H:%M:%S")
    
    dbArchivePaths = [] 
    for key, diagnosticBundle in dataDict.items() :
        logger.debug(f'AEDWIP key : {key}, diagnosticBundle.diagnosis {diagnosticBundle.diagnosis}')
        archivePath =  saveDiagnosticBundle( outDir, diagnosticBundle)
        dbArchivePaths.append(archivePath)
        
    archiveDict['diagnosticBundles'] = dbArchivePaths
    
   # save in json format
    filePath = f'{outDir}/archive.json'
    with open(filePath, "w") as f:
        # setting indent generates pretty print format
        json.dump(archiveDict, f,  indent=4)  
        logger.warning(f'saved : {filePath}') 


