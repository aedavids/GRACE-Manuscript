def saveDiagnosticBundleMetaData( saveDict : dict,  db : DiagnosticBundle) -> None:
    '''
    TODO
    '''
    saveDict['diagnosis'] = db.diagnosis
    saveDict['realCountPath'] = db.realCountPath
    saveDict['realMetaPath'] = db.realMetaPath
    saveDict['simulatedCountPath'] = db.simulatedCountPath
    saveDict['simulatedMetaPath'] = db.simulatedMetaPath
    saveDict['categories'] = db.categories

################################################################################ 
def saveTrainedModel( outDir: str, saveDict : dict, mb : ModelBundle) -> None :
    ''' 
    TODO
    
    save state generated by train() 
    
    arguments:
        outDir : location to save model and labelEncoder in joblib format
            saveDict has path to model and encoder files

    '''
    outDir = f'{outDir}/trainedModel'
    os.makedirs(outDir, exist_ok=True)
    modelDict = dict()
    
    modelPath = f'{outDir}/model.joblib'
    joblib.dump(mb.model, modelPath)
    modelDict['modelPath'] = modelPath
    logger.warning(f'saved {modelPath}')
    
    # labelEncoderPath = f'{outDir}/labelEndoder.joblib'
    # joblib.dump(mb.labelEncoder, labelEncoderPath)

    # 
    
    # 12/12/25 bug. add a list to archive dict not a string of a list
    #modelDict['orderedCategories'] = f'{list(mb.orderedCategories)}'
    modelDict['orderedCategories'] = list(mb.orderedCategories)
    
    features = mb.X.columns.to_list()
    modelDict['features'] = features
    sampleIds = mb.X.index.to_list()
    modelDict['sampleIds'] = sampleIds
    
    modelDict['X.shape'] = mb.X.shape
    
    saveDict['trainedModel'] = modelDict
    
################################################################################
def saveDiagnosticBundle( 
                         outDir: str, 
                         db : DiagnosticBundle) -> str :
    '''
    TODO
    
    output will be saved in f'{outDir}{db.diagnosis}'
    
    builds
    
    returns path to json archive file. 
    '''
    logger.debug(f'AEDWIP db.diagnosis {db.diagnosis}')

    outDir = f'{outDir}/{db.diagnosis}'
    os.makedirs(outDir, exist_ok=True)
    
    # everything in saveDict will eventuall 
    # be convert to json format and saved to disk
    saveDict = dict()
    
    from datetime import datetime
    now = datetime.now()
    saveDict['runTimeStamp'] =  now.strftime("%Y-%m-%d %H:%M:%S")
    
    saveDiagnosticBundleMetaData(saveDict, db)
    # logger.deb(f'AEDWIP saveDiagnosticBundleMetaData\n {pp.pformat(saveDict)}')
    
    # add the results from evaluate()
    for attribute in ['simTrain', 'simVal', 'simTest', 'real']:
        mb = getattr(db, attribute)
        key = f'{attribute}Results'
        saveDict[key] = mb.resultsDict
        # logger.debug(f'\nAEDWIP key: {key}')
        # logger.debug(f'AEDWIP mb.resultsDict\n {pp.pformat(mb.resultsDict)}')
    
    saveTrainedModel(outDir , saveDict, db.simTrain)
    
    # save in json format
    filePath = f'{outDir}/archive_{db.diagnosis}.json'
    with open(filePath, "w") as f:
        # setting indent generates pretty print format
        json.dump(saveDict, f,  indent=4)  
        logger.warning(f'saved : {filePath}')    
    
    return filePath


