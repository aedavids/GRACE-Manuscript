def saveWrappedDataFrameImage(
    df: pd.DataFrame,
    outPath: str | Path,
    dpi: int = 300,
    maxRows: int | None = 20,
    showIndex: bool = False,
    wrapWidthByColumn: dict[str, int] | None = None,
    fontSize: int = 10
) -> None:
    """
    generated by chatGPT
    Save a pandas DataFrame as PNG and PDF images, with optional
    per-column text wrapping.

    Args:
        df:
            DataFrame to render.
        outPath:
            Output file path. Example: "results/myTable.png"
        dpi:
            Figure resolution.
        maxRows:
            Optional row limit for display.
        showIndex:
            If True, display the DataFrame index.
        wrapWidthByColumn:
            Dictionary mapping column name -> wrap width in characters.
            Example: {"HUGO": 18, "bioType": 35}
        fontSize:
            Table font size.
    """
    outFile = Path(outPath)
    outFile.parent.mkdir(parents=True, exist_ok=True)

    renderDF = df.copy()
    if maxRows is not None:
        renderDF = renderDF.head(maxRows)

    if wrapWidthByColumn is None:
        wrapWidthByColumn = {}

    wrappedDF = renderDF.copy()

    for col in wrappedDF.columns:
        if col in wrapWidthByColumn:
            wrapWidth = wrapWidthByColumn[col]
            wrappedDF[col] = wrappedDF[col].map(
                lambda value: fill(str(value), width=wrapWidth)
            )
        else:
            wrappedDF[col] = wrappedDF[col].map(str)

    nRows = len(wrappedDF) + 1
    nCols = len(wrappedDF.columns) + (1 if showIndex else 0)

    # Estimate required line count per row after wrapping
    maxLinesPerRow: list[int] = []
    for rowIdx in range(len(wrappedDF)):
        rowValues = [str(x) for x in wrappedDF.iloc[rowIdx].tolist()]

        if showIndex:
            rowValues = [str(wrappedDF.index[rowIdx])] + rowValues

        maxLines = max(value.count("\n") + 1 for value in rowValues)
        maxLinesPerRow.append(maxLines)

    totalRowUnits = 1 + sum(maxLinesPerRow)  # +1 for header row

    figWidth = max(8.0, nCols * 2.0)
    figHeight = max(1.5, totalRowUnits * 0.38)

    fig, ax = plt.subplots(figsize=(figWidth, figHeight))
    ax.axis("off")

    table = ax.table(
        cellText=wrappedDF.values,
        rowLabels=[str(idx) for idx in wrappedDF.index] if showIndex else None,
        colLabels=[str(col) for col in wrappedDF.columns],
        loc="center"
    )

    table.auto_set_font_size(False)
    table.set_fontsize(fontSize)
    table.scale(1.0, 1.2)

    # Make row heights larger for rows with wrapped text
    for rowNumber, maxLines in enumerate(maxLinesPerRow, start=1):
        baseHeight = table[(rowNumber, 0)].get_height()
        newHeight = baseHeight * max(1.0, maxLines * 1.15)

        colStart = -1 if showIndex else 0
        colEnd = len(wrappedDF.columns) - 1

        for colNumber in range(colStart, colEnd + 1):
            if (rowNumber, colNumber) in table._cells:
                table[(rowNumber, colNumber)].set_height(newHeight)

    plt.tight_layout()

    cleanOutFile = Path(outFile).with_suffix("")
    pngOutFile = cleanOutFile.with_suffix(".png")
    pdfOutFile = cleanOutFile.with_suffix(".pdf")

    fig.savefig(pngOutFile, dpi=dpi, bbox_inches="tight")
    fig.savefig(pdfOutFile, dpi=dpi, bbox_inches="tight")
    plt.close(fig)

    print(f"saved: {pngOutFile}")
    print(f"saved: {pdfOutFile}")
    
###############################################################################
def stripMatplotlibSuffix(fname: str) -> str:
    """
    Remove a recognized Matplotlib output suffix from a filename.
    
    this insures that fig.savefit(fname, format="png") will be saved with the 
    correct filename suffix

    Parameters
    ----------
    fname
        Input filename or path.

    Returns
    -------
    str
        Filename with the Matplotlib suffix removed if present.
        Otherwise returns the original filename.
    """
    path = Path(fname)

    if path.suffix.lower() in MATPLOTLIB_SUFFIXES:
        return str(path.with_suffix(""))

    return str(path)

###############################################################################
def urlify(s : str) -> str:
    '''
    useful function for converting plot titles to strings
    https://stackoverflow.com/a/1007615/4586180

    print(urlify("I can't get no satisfaction!"))
    Prints: I-cant-get-no-satisfaction"
    '''

    # Remove all non-word characters (everything except numbers and letters)
    s = re.sub(r"[^\w\s]", '', s)

    # Replace all runs of whitespace with a single dash
    s = re.sub(r"\s+", '-', s)
    
    return s

###############################################################################
def wrapCellText(value: object, width: int = 30) -> str:
    return fill(str(value), width=width)
