def heightForAspectRatio(width : float, ratio : float=4/3) -> float :
    ''' 
    resize easy of use function
    '''
    height = width/ratio
    return height

################################################################################
def calculateAspectRatio(fig : plt.Figure) -> float :
    '''
    resize easy of use function
    '''
    w,h = fig.get_size_inches()
    ret = w/h
    
    return ret

