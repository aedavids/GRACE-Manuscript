def displayFigure( fig : figure) -> None:
    '''
    creates a new figure and causes it to display
    
    If you are using a jupyter notebook use 
    
    from IPython.display import display

    '''
    
    # Figure
    # represents the entire plots, axes, titles, ledgends
    # It does not konw about windows, notebooks, or GUIs

    # FigureCanvas
    # the drawing surface of the figure
    # responsible for turning the figure into pixels
    # different canvas objects exits for different back ends
    # Agg -> raster images, PDF -> vector

    # canvas manager (figureManager)
    # Provides the windowing / interaction layer: e.g. a toolbar, 
    # resizing a window, responding to key presses, embedding in Jupyter, etc
    # Exists only for interactive backends (TkAgg, QtAgg, WebAgg, notebook, etc.

    # redisplay
    # Create a new, temporary figure
    new_fig = plt.figure()

    # Get the manager from the new figure
    new_manager = new_fig.canvas.manager

    # Set the manager of the original figure to the new manager
    fig.canvas.manager = new_manager

    # Set the canvas of the new figure to the canvas of the original figure
    new_manager.canvas = fig.canvas

    # Set the figure of the new manager's canvas to the original figure
    #fig.canvas.manager.toolbar.canvas = fig.canvas

    # Show the re-attached figure
    plt.show(block=True)
    
