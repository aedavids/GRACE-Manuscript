def changeYlabels(geneMapDict : dict[str, str], ax : plt.axes) -> None:
    '''
    geneMapDict keys yaxis ytickLables are replaced with geneMapDict value

    '''
    # yLabels = list([label.get_text() for label in ax.get_yticklabels()])
    yTicks = ax.get_yticks()
    yLabels = [label.get_text() for label in ax.get_yticklabels()]
    logger.debug(f'AEDWIP yLables {list(yLabels)}')
    
    newYLabels = [geneMapDict[label] for label in yLabels]
    logger.debug(f'AEDWIP yLables {list(newYLabels)}')

    ax.set_yticks( yTicks )
    ax.set_yticklabels(list(newYLabels))

